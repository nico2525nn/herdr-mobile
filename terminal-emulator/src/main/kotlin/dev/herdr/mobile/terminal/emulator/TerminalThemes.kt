package dev.herdr.mobile.terminal.emulator

private fun rgb(r: Int, g: Int, b: Int) = TerminalColor(r, g, b)

private fun scheme(
    background: TerminalColor,
    foreground: TerminalColor,
    ansi: List<TerminalColor>,
    cursor: TerminalColor = foreground,
    selection: TerminalColor = foreground.copy(alpha = 77),
): TerminalColorScheme {
    require(ansi.size == 16) { "ansi palette must hold exactly 16 entries" }
    return TerminalColorScheme(
        background = background,
        foreground = foreground,
        cursor = cursor,
        selection = selection,
        ansi = ansi,
    )
}

